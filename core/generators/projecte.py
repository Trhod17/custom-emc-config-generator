import json
import os

from packaging.version import Version

from core.generators.generator import Generator
from core.modpack import ModPack


class ProjecteOld(Generator):
    def __init__(self):
        super().__init__()
        self.output_file_name = "custom_emc.cfg"
        self.pack: ModPack

    def setup(self, pack: ModPack):
        self.pack = pack
        return self

    def create_file(self, registry):
        output_dir = self.get_path(
            self.pack.modpack_id, self.pack.modpack_version, "projecte"
        )
        if os.path.isfile(output_dir + self.output_file_name):
            os.remove(output_dir + self.output_file_name)

        if not os.path.exists(output_dir):
            os.makedirs(output_dir)

        with open(output_dir + self.output_file_name, "w") as text_file:
            text_file.writelines(
                "#####################################\n"
                "# ProjectE Custom EMC Config        #\n"
                "# Generated By EMC Config Generator #\n"
                "#####################################\n"
                "\n"
            )
            for item in registry.get_all_items().values():
                text_file.writelines(
                    f"S:{item.mod}:{item.name}\nM:{item.meta}\nE:{item.emc}\n\n"
                )

        text_file.close()


class Projecte(Generator):
    def __init__(self):
        super().__init__()
        self.output_file_name = "custom_emc.json"
        self.pack: ModPack

    def setup(self, pack: ModPack):
        self.pack = pack
        return self

    def create_file(self, registry):
        output_dir = self.get_path(
            self.pack.modpack_id, self.pack.modpack_version, "projecte"
        )
        if os.path.isfile(output_dir + self.output_file_name):
            os.remove(output_dir + self.output_file_name)

        if not os.path.exists(output_dir):
            os.makedirs(output_dir)

        data = {
            "line1": "#####################################\n",
            "line2": "# ProjectE Custom EMC Config        #\n",
            "line3": "# Generated By EMC Config Generator #\n",
            "line4": "#####################################\n",
            "entries": [],
        }

        old = Version("1.10")
        new = Version("1.13")
        game_version = Version(self.pack.game_version)
        # log.debug(f"{registry.get_all_items().values()}")
        if old <= game_version < new:
            for item in registry.get_all_items().values():
                # log.debug(f"This is running for {self.pack.name}")
                data["entries"].append(
                    {
                        "item": f"{item.mod}:{item.name}|{item.meta}",
                        "emc": f"{item.emc}",
                    }
                )

        if game_version >= new:
            for item in registry.get_all_items().values():
                data["entries"].append(
                    {"item": f"{item.mod}:{item.name}", "emc": f"{item.emc}"}
                )

        with open(output_dir + self.output_file_name, "w") as file:
            json.dump(data, file, indent=4)

        file.close()
