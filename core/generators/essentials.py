import csv
import os

from core.configpack import ConfigPack
from core.generators.generator import Generator


class EssentialsWorth(Generator):
    def __init__(self):
        super().__init__()
        self.output_file_name = "worth.yml"
        self.pack: ConfigPack

    def setup(self, pack):
        self.pack = pack
        return self

    def create_file(self, registry):
        output_dir = self.get_path(
            self.pack.cpid, self.pack.modpack_version, "essentials"
        )

        if os.path.isfile(output_dir + self.output_file_name):
            os.remove(output_dir + self.output_file_name)

        if not os.path.exists(output_dir):
            os.makedirs(output_dir)

        ids = {}

        for item in registry.get_all_items().values():
            if item.id in ids:
                ids[item.id][item.meta] = item.emc
                continue

            ids[item.id] = {item.meta: item.emc}

        with open(output_dir + self.output_file_name, "w") as text_file:
            text_file.writelines(
                "#####################################\n"
                "# Essentials Worth.yml              #\n"
                "# Generated By EMC Config Generator #\n"
                "#####################################\n"
            )
            text_file.write("worth:\n")
            for id, metadata in ids.items():
                text_file.write(f"  x{id}:\n")
                for meta, value in metadata.items():
                    text_file.writelines(f"      {meta}: {value}\n")

            text_file.close()


class EssentialsItems(Generator):
    def __init__(self):
        super().__init__()
        self.output_file_name = "items.csv"
        self.pack: ConfigPack

    def setup(self, pack):
        self.pack = pack
        return self

    def create_file(self, registry):
        output_dir = self.get_path(
            self.pack.cpid, self.pack.modpack_version, "essentials"
        )

        if os.path.isfile(output_dir + self.output_file_name):
            os.remove(output_dir + self.output_file_name)

        if not os.path.exists(output_dir):
            os.makedirs(output_dir)

        with open(output_dir + self.output_file_name, "w") as csv_file:
            csvwriter = csv.writer(csv_file)
            csvwriter.writerow(["#item", "id", "metadata"])
            for item in registry.get_all_items().values():
                csvwriter.writerow(
                    [item.name.replace("_", "").strip(), item.id, item.meta]
                )
            csv_file.close()
