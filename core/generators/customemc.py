import os

from core.generators.generator import Generator
from core.modpack import ModPack


class CustomEmc(Generator):
    def __init__(self):
        super().__init__()
        self.output_file_name = "CustomEMC.cfg"
        self.pack: ModPack

    def setup(self, pack: ModPack):
        self.pack = pack
        return self

    def create_file(self, registry):
        output_dir = self.get_path(
            self.pack.modpack_id, self.pack.modpack_version, "customemc"
        )
        if os.path.isfile(output_dir + self.output_file_name):
            os.remove(output_dir + self.output_file_name)

        if not os.path.exists(output_dir):
            os.makedirs(output_dir)

        with open(output_dir + self.output_file_name, "w") as text_file:
            text_file.writelines(
                "#####################################\n"
                "# Custom EMC Config                 #\n"
                "# Generated By EMC Config Generator #\n"
                "#####################################\n"
            )
            for item in registry.get_all_items().values():
                text_file.write(f"#{item.name}\n")
                if item.meta == 0:
                    text_file.write(f"AddEMC {item.id},{int(round(item.emc, 0))}\n")

                if item.meta > 0:
                    text_file.write(
                        f"AddEMC {item.id}:{item.meta},{int(round(item.emc, 0))}\n"
                    )

                if item.custom_emc_extras:
                    if item.num_dusts is not None and item.dust_tier is not None:
                        text_file.write(
                            f"AddCovRepairable {item.id},{item.num_dusts},{item.dust_tier}\n"
                        )

                    if item.add_as_fuel:
                        if item.meta == 0:
                            text_file.write(f"AddAsFuel {item.id}\n")

                        if item.meta > 0:
                            text_file.write(f"AddAsFuel {item.id}:{item.meta}\n")

                    if item.unrepairable:
                        text_file.write(f"AddUnrepairable {item.id}\n")

                    if item.add_ore:
                        text_file.write(f"AddOreBlock {item.id}\n")

        text_file.close()
